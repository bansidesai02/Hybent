/// <reference lib="webworker" />
import { addRoute, precache, cleanupOutdatedCaches, createHandlerBoundToURL } from 'workbox-precaching'
import { NavigationRoute, registerRoute } from 'workbox-routing'
import { clientsClaim } from 'workbox-core'

declare const self: any

// injectManifest (a custom service worker, unlike the auto-wired generateSW
// strategy) needs this pair spelled out explicitly, or a newly deployed
// worker installs but sits waiting in the background — potentially
// indefinitely — while any tab left open from before the deploy keeps being
// served by the OLD worker's stale precached bundle. skipWaiting activates
// the new worker as soon as it finishes installing; clientsClaim then hands
// it control of already-open tabs immediately, instead of only new ones.
self.skipWaiting()
clientsClaim()

cleanupOutdatedCaches()

// Precache list generated by workbox
precache(self.__WB_MANIFEST)

/* Every page load asks the server first, so a refresh always shows the latest
   deploy. The cached app shell is only the fallback: offline, or a connection
   too slow to answer in 4 seconds. API calls and the crawler-only SEO pages
   never come through here. This must be registered before addRoute(), or the
   precache would answer "/" with the old index.html. */
const appShell = createHandlerBoundToURL('index.html')
registerRoute(
  new NavigationRoute(
    async (options: any) => {
      try {
        return await Promise.race([
          fetch(options.request),
          new Promise<Response>((_, reject) => setTimeout(() => reject(new Error('slow')), 4000)),
        ])
      } catch {
        return appShell(options)
      }
    },
    { denylist: [/^\/v1\//, /^\/api\//, /^\/_seo\//, /\.[a-z0-9]+$/i] },
  )
)

// Hashed JS and CSS: served from the precache, safe because a new deploy has new names.
addRoute()

// Notifications are shown only inside Hybent (the bell panel and in-app
// toasts). This worker used to show Firebase push notifications as OS pop-ups;
// that's gone, and any browser that allowed them earlier is unsubscribed here
// so no push can reach it. (The file keeps its old name: vite.config.ts builds
// the service worker from it.)
self.addEventListener('activate', (event: any) => {
  event.waitUntil(
    self.registration.pushManager
      ?.getSubscription()
      .then((subscription: any) => subscription?.unsubscribe())
      .catch(() => undefined)
  )
})
